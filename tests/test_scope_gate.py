# --- write_run_profile --------------------------------------------------

def _base_profile(tmp_path: Path) -> Path:
    path = tmp_path / "review_profile.toml"
    path.write_text(
        'exclude_files = [\n    "yarn.lock",\n    "*.min.js",\n]\n\n'
        "max_code_tokens = 24000\n\n"
        '[prompt_vars]\n'
        'self_id = """\nYou are CodePulse.\n"""\n',
        encoding="utf-8",
    )
    return path


def test_write_run_profile_merges_and_preserves(tmp_path):
    base = _base_profile(tmp_path)
    run_dir = tmp_path / "run"
    out = scope_gate.write_run_profile(base, run_dir, ["node_modules/x.js", "yarn.lock"])

    conf = tomllib.loads(out.read_text(encoding="utf-8"))
    # Base entries preserved, new entry added, no duplicate of yarn.lock.
    assert conf["exclude_files"] == ["yarn.lock", "*.min.js", "node_modules/x.js"]
    # The rest of the profile survives intact.
    assert conf["max_code_tokens"] == 24000
    assert "You are CodePulse." in conf["prompt_vars"]["self_id"]


def test_write_run_profile_handles_profile_without_exclude(tmp_path):
    base = tmp_path / "p.toml"
    base.write_text("max_code_tokens = 100\n", encoding="utf-8")
    out = scope_gate.write_run_profile(base, tmp_path / "r", ["dist/a.js"])
    conf = tomllib.loads(out.read_text(encoding="utf-8"))
    assert conf["exclude_files"] == ["dist/a.js"]
    assert conf["max_code_tokens"] == 100


def test_write_run_profile_escapes_special_paths(tmp_path):
    base = _base_profile(tmp_path)
    out = scope_gate.write_run_profile(base, tmp_path / "r", ['weird "quoted"/back\\slash.js'])
    # Must still be valid TOML with the exact path preserved.
    conf = tomllib.loads(out.read_text(encoding="utf-8"))
    assert 'weird "quoted"/back\\slash.js' in conf["exclude_files"]


def test_apply_scope_gate_snapshot_rewrites_profile_env(tmp_path, monkeypatch):
    import codepulse_app.server as server

    monkeypatch.setattr(server, "RUNS_DIR", tmp_path / "runs")
    run_id = "20260725-140000-abcd1234"
    server.run_dir(run_id).mkdir(parents=True)

    repo = tmp_path / "repo"
    _write(repo, "app/server.py")
    _write(repo, "node_modules/dep/index.js")
    _write(repo, "yarn.lock", "lock\n")
    server.atomic_write_json(
        server.meta_path(run_id),
        {"id": run_id, "changed_files": ["app/server.py", "node_modules/dep/index.js", "yarn.lock"]},
    )

    env: dict[str, str] = {}
    payload = {"mode": "refs", "refs": snapshot.SNAPSHOT_REFS}
    server.apply_scope_gate(run_id, repo, payload, env)

    assert env["GITO_EXTRA_PROJECT_CONFIG"].endswith("review_profile.run.toml")
    conf = tomllib.loads(Path(env["GITO_EXTRA_PROJECT_CONFIG"]).read_text(encoding="utf-8"))
    assert "node_modules/dep/index.js" in conf["exclude_files"]
    meta = server.read_json(server.meta_path(run_id), {})
    assert meta["scope_gate"]["excluded_count"] == 2
    assert meta["scope_gate"]["kept_count"] == 1


def test_apply_scope_gate_leaves_normal_pr_untouched(tmp_path, monkeypatch):
    import codepulse_app.server as server

    monkeypatch.setattr(server, "RUNS_DIR", tmp_path / "runs")
    run_id = "20260725-141000-beef0001"
    server.run_dir(run_id).mkdir(parents=True)
    server.atomic_write_json(
        server.meta_path(run_id), {"id": run_id, "changed_files": ["yarn.lock"]}
    )

    env: dict[str, str] = {}
    server.apply_scope_gate(run_id, tmp_path, {"mode": "working"}, env)

    # A normal PR is never gated: env untouched, no scope_gate meta written.
    assert "GITO_EXTRA_PROJECT_CONFIG" not in env
    assert "scope_gate" not in server.read_json(server.meta_path(run_id), {})


def test_real_review_profile_round_trips():
    # The shipped profile must merge cleanly (it carries multi-line prompts).
    real = Path(__file__).resolve().parent.parent / "codepulse_app" / "review_profile.toml"
    import tempfile

    with tempfile.TemporaryDirectory() as d:
        out = scope_gate.write_run_profile(real, Path(d), ["node_modules/x.js"])
        conf = tomllib.loads(out.read_text(encoding="utf-8"))
    assert "node_modules/x.js" in conf["exclude_files"]
    # Baseline entries from the shipped profile are still present.
    assert "poetry.lock" in conf["exclude_files"]
    assert conf["prompt_vars"]["self_id"].strip().startswith("You are CodePulse")
