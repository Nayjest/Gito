# --- classification -----------------------------------------------------

def test_noise_globs_match_vendored_generated_and_lockfiles():
    m = scope_gate._matches_noise
    assert m("frontend/node_modules/react/index.js") == "vendored"
    assert m("vendor/pkg/mod.go") == "vendored"
    assert m("app/static/app.min.js") == "minified"
    assert m("api/pb/user_pb2.py") == "generated-code"
    assert m("package-lock.json") == "lockfile"
    assert m("data/exports.csv") == "data-asset"
    assert m("dist/bundle.js") == "build-output"


def test_source_and_config_are_not_noise():
    m = scope_gate._matches_noise
    # Ordinary source keeps its LLM coverage.
    assert m("codepulse_app/server.py") is None
    assert m("src/routes/handler.ts") is None
    # Config files can carry real signal -> never gated by pattern.
    assert m("config/settings.json") is None
    assert m("deploy/k8s.yaml") is None
    assert m("pyproject.toml") is None


def test_vendored_dir_matches_at_root_and_nested():
    m = scope_gate._matches_noise
    assert m("node_modules/left-pad/index.js") == "vendored"
    assert m("a/b/node_modules/x.js") == "vendored"
    # A file merely *named* like the marker is not a directory match.
    assert m("src/node_modules_helper.py") is None


# --- plan_exclusions ----------------------------------------------------

def _write(root: Path, rel: str, content: str = "x = 1\n") -> None:
    path = root / rel
    path.parent.mkdir(parents=True, exist_ok=True)
    path.write_text(content, encoding="utf-8")


def test_plan_excludes_noise_keeps_source(tmp_path):
    _write(tmp_path, "app/server.py")
    _write(tmp_path, "app/utils.py")
    _write(tmp_path, "node_modules/dep/index.js")
    _write(tmp_path, "static/app.min.js", "a" * 5000)
    _write(tmp_path, "yarn.lock", "lockfile\n")

    files = ["app/server.py", "app/utils.py", "node_modules/dep/index.js",
             "static/app.min.js", "yarn.lock"]
    plan = scope_gate.plan_exclusions(tmp_path, files)

    excluded = {e["path"] for e in plan.excluded}
    assert excluded == {"node_modules/dep/index.js", "static/app.min.js", "yarn.lock"}
    assert plan.kept_count == 2
    assert plan.est_tokens_saved > 0


def test_plan_sniffs_generated_marker_in_source(tmp_path):
    _write(
        tmp_path,
        "api/schema.py",
        "# @generated by codegen -- DO NOT EDIT\nclass Schema:\n    pass\n",
    )
    plan = scope_gate.plan_exclusions(tmp_path, ["api/schema.py"])
    assert [e["reason"] for e in plan.excluded] == ["generated-marker"]
    assert plan.kept_count == 0


def test_plan_flags_large_low_newline_blob(tmp_path):
    # 300 KB with a single newline -> minified/serialized blob.
    _write(tmp_path, "assets/data.txt", "z" * 300_000 + "\n")
    plan = scope_gate.plan_exclusions(tmp_path, ["assets/data.txt"])
    assert [e["reason"] for e in plan.excluded] == ["minified-blob"]


def test_plan_keeps_normal_source_with_markers_absent(tmp_path):
    _write(tmp_path, "svc/pay.py", "def charge(amount):\n    return amount * 2\n")
    plan = scope_gate.plan_exclusions(tmp_path, ["svc/pay.py"])
    assert plan.excluded == []
    assert plan.kept_count == 1


def test_plan_missing_file_is_kept_not_hidden(tmp_path):
    # A path we can't stat (deleted, or outside the tree) must never be excluded.
    plan = scope_gate.plan_exclusions(tmp_path, ["ghost/only_source.py"])
    assert plan.excluded == []
    assert plan.kept_count == 1


def test_plan_meta_is_compact_and_serializable(tmp_path):
    _write(tmp_path, "yarn.lock", "lock\n")
    plan = scope_gate.plan_exclusions(tmp_path, ["yarn.lock"])
    meta = plan.to_meta()
    assert meta["enabled"] is True
    assert meta["excluded_count"] == 1
    assert meta["reasons"] == {"lockfile": 1}
    import json

    json.dumps(meta)  # must be JSON-serializable


